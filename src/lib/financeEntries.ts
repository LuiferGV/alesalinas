import type { Expense, FinanceEntry, PaymentEntry } from "../types/clinic";

const FINANCE_DATE_LINKED_PAYMENT_NOTES = new Set([
  "Pago registrado junto con la atencion.",
  "Pago inicial registrado junto con el cargo."
]);

export function describeFinanceStatus(totalAmount: number, paidAmount: number) {
  const pendingAmount = Math.max(totalAmount - paidAmount, 0);
  if (totalAmount === 0) return "No corresponde cobrar";
  if (pendingAmount === 0) return "Cobrado";
  if (paidAmount > 0) return "Pago parcial";
  return "Pendiente con monto";
}

export function sortPaymentsByDateDesc<T extends { date: string }>(payments: T[]) {
  return [...payments].sort((left, right) => right.date.localeCompare(left.date));
}

export function getPaymentsTotal(payments: PaymentEntry[]) {
  return payments.reduce((sum, payment) => sum + Math.max(payment.amount || 0, 0), 0);
}

export function createPaymentEntry({
  id,
  date,
  amount,
  method,
  note,
  fromMarketing
}: {
  id: string;
  date: string;
  amount: number;
  method?: string;
  note?: string;
  fromMarketing?: boolean;
}): PaymentEntry {
  return {
    id,
    date,
    amount: Math.max(amount || 0, 0),
    method: method?.trim() || "Otro",
    note: note?.trim() || "",
    fromMarketing: Boolean(fromMarketing)
  };
}

export function createLegacyPayments(entry: Pick<FinanceEntry, "id" | "date" | "paidAmount" | "description">) {
  if ((entry.paidAmount || 0) <= 0) return [];

  return [
    createPaymentEntry({
      id: `${entry.id}-legacy-payment`,
      date: entry.date,
      amount: entry.paidAmount,
      method: "Importado",
      note: entry.description || "Pago importado desde un registro anterior."
    })
  ];
}

function isLegacyPaymentCreatedFromFinanceEntry(
  entry: Pick<FinanceEntry, "id">,
  payment: PaymentEntry
) {
  const legacyPaymentId = `${entry.id}-legacy-payment`;

  return (
    payment.method === "Importado" &&
    (payment.id === legacyPaymentId || payment.id.startsWith(`${legacyPaymentId}-`))
  );
}

/**
 * Moves payments that were created together with a finance entry when its date changes.
 *
 * Only payments carrying one of the markers generated by the app (or the
 * deterministic legacy-import id) follow the finance date. Later/manual
 * payments have no such marker and remain on their own collection date.
 */
export function relocateFinanceDateLinkedPayments(
  entry: Pick<FinanceEntry, "id" | "date" | "payments">,
  nextFinanceDate: string
) {
  const nextDate = nextFinanceDate.trim();

  if (!nextDate) return entry.payments;

  return entry.payments.map((payment) => {
    const wasCreatedWithEntry = FINANCE_DATE_LINKED_PAYMENT_NOTES.has(payment.note.trim());
    const wasImportedWithEntry = isLegacyPaymentCreatedFromFinanceEntry(entry, payment);

    if ((!wasCreatedWithEntry && !wasImportedWithEntry) || payment.date === nextDate) {
      return payment;
    }

    return { ...payment, date: nextDate };
  });
}

/**
 * Moves patient costs created together with a treatment when that treatment's
 * date changes. A linked cost is created as part of that treatment and the UI
 * edits it through the treatment, so its accounting date follows the treatment.
 */
export function relocateTreatmentDateLinkedExpenses(
  expenses: Expense[],
  treatmentId: string,
  previousTreatmentDate: string,
  nextTreatmentDate: string
) {
  const previousDate = previousTreatmentDate.trim();
  const nextDate = nextTreatmentDate.trim();

  if (!treatmentId || !previousDate || !nextDate || previousDate === nextDate) return expenses;

  return expenses.map((expense) =>
    expense.linkedTreatmentId === treatmentId && expense.date !== nextDate
      ? { ...expense, date: nextDate }
      : expense
  );
}

export function syncFinanceEntry(entry: FinanceEntry): FinanceEntry {
  const payments = sortPaymentsByDateDesc(
    (entry.payments ?? []).filter((payment) => Number(payment.amount || 0) > 0)
  ).map((payment) => ({
    ...payment,
    amount: Number(payment.amount || 0),
    method: payment.method?.trim() || "Otro",
    note: payment.note || "",
    fromMarketing: Boolean(payment.fromMarketing)
  }));

  const totalAmount = Math.max(Number(entry.totalAmount || 0), 0);
  const paidAmount = getPaymentsTotal(payments);
  const pendingAmount = Math.max(totalAmount - paidAmount, 0);

  return {
    ...entry,
    totalAmount,
    payments,
    paidAmount,
    pendingAmount,
    status: describeFinanceStatus(totalAmount, paidAmount)
  };
}

export function createFinanceEntry(entry: Omit<FinanceEntry, "status" | "paidAmount" | "pendingAmount">): FinanceEntry {
  return syncFinanceEntry({
    ...entry,
    status: "",
    paidAmount: 0,
    pendingAmount: 0
  });
}

export function getFinanceActivityDate(entry: FinanceEntry) {
  const latestPaymentDate = entry.payments[0]?.date;
  if (!latestPaymentDate) return entry.date;
  return latestPaymentDate > entry.date ? latestPaymentDate : entry.date;
}

export function sortFinancesByActivity(entries: FinanceEntry[]) {
  return [...entries].sort((left, right) => getFinanceActivityDate(right).localeCompare(getFinanceActivityDate(left)));
}

export function appendPaymentToFinance(entry: FinanceEntry, payment: PaymentEntry) {
  return syncFinanceEntry({
    ...entry,
    payments: [payment, ...(entry.payments ?? [])]
  });
}

export function replacePaymentInFinance(entry: FinanceEntry, payment: PaymentEntry) {
  return syncFinanceEntry({
    ...entry,
    payments: entry.payments.map((current) => (current.id === payment.id ? payment : current))
  });
}

export function removePaymentFromFinance(entry: FinanceEntry, paymentId: string) {
  return syncFinanceEntry({
    ...entry,
    payments: entry.payments.filter((payment) => payment.id !== paymentId)
  });
}

export function replacePaymentInFinances(
  entries: FinanceEntry[],
  financeId: string,
  payment: PaymentEntry
) {
  return entries.map((entry) =>
    entry.id === financeId ? replacePaymentInFinance(entry, payment) : entry
  );
}

export function removePaymentFromFinances(
  entries: FinanceEntry[],
  financeId: string,
  paymentId: string
) {
  return entries.map((entry) =>
    entry.id === financeId ? removePaymentFromFinance(entry, paymentId) : entry
  );
}
